    def test_chatgpt_removed_runtime_restores_baseline_without_reviving_saved_wrappers(self):
        launch,application=self.chatgpt_ready()
        desktop=self.p.path(mod.CHATGPT_DESKTOP);cli=self.p.path(".local/bin/chatgpt")
